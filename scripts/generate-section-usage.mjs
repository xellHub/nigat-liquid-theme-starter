import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = join(fileURLToPath(new URL("..", import.meta.url)));
const blocksDir = join(root, "blocks");
const checkOnly = process.argv.includes("--check");
const registrySource = readFileSync(join(root, "scripts/validate-section-library.mjs"), "utf8");
const mirrors = [
  ...registrySource.matchAll(
    /\[\s*['"](section-library\/[^'"]+\.liquid)['"]\s*,\s*['"]([^'"]+\.liquid)['"],?\s*\]/g
  ),
].map((match) => [match[1], match[2]]);
const errors = [];

function fingerprint(paths) {
  const hash = createHash("sha256");
  for (const path of paths.sort())
    hash.update(`${relative(root, path)}\0${readFileSync(path, "utf8")}\0`);
  return hash.digest("hex");
}

function schemaFor(path) {
  const source = readFileSync(path, "utf8");
  const match = source.match(/\{%-?\s*schema\s*-?%\}([\s\S]*?)\{%-?\s*endschema\s*-?%\}/);
  if (!match) throw new Error(`${relative(root, path)} has no schema`);
  return JSON.parse(match[1]);
}

function cell(value) {
  if (value === undefined || value === null || value === "") return "—";
  const text = typeof value === "object" ? JSON.stringify(value) : String(value);
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function settingsTable(settings = []) {
  const rows = settings
    .filter((setting) => setting.id)
    .map(
      (setting) =>
        `| \`${cell(setting.id)}\` | ${cell(setting.type)} | ${cell(setting.default)} | ${cell(setting.label || setting.content)} |`
    );
  if (!rows.length) return "_No settings._";
  return ["| ID | Type | Default | Editor label |", "| --- | --- | --- | --- |", ...rows].join(
    "\n"
  );
}

function childTypes(schema) {
  return (schema.blocks || []).map((block) => block.type).filter(Boolean);
}

function blockDescription(type, inlineBlock) {
  if (type === "@theme")
    return "Any public foundational block documented in `guide/fundamental-blocks.md`.";
  if (type === "@app") return "A Shopify app block.";
  const schema =
    inlineBlock ||
    (existsSync(join(blocksDir, `${type}.liquid`))
      ? schemaFor(join(blocksDir, `${type}.liquid`))
      : null);
  if (!schema) return `${type}; no child blocks.`;
  const children = childTypes(schema);
  return `${schema.name || type}${children.length ? `; children: ${children.map((child) => `\`${child}\``).join(", ")}` : "; no child blocks"}.`;
}

function collectBlockSchemas(types, rootSchema = null, found = new Map()) {
  for (const type of types) {
    if (type.startsWith("@") || found.has(type)) continue;
    const inlineBlock = rootSchema?.blocks?.find((b) => b.type === type && b.settings);
    if (inlineBlock) {
      found.set(type, inlineBlock);
      continue;
    }
    const path = join(blocksDir, `${type}.liquid`);
    if (existsSync(path)) {
      const schema = schemaFor(path);
      found.set(type, schema);
      collectBlockSchemas(childTypes(schema), null, found);
    }
  }
  return found;
}

function documentFor(libraryFile, runtimeFile) {
  const schema = schemaFor(join(root, libraryFile));
  const types = childTypes(schema);
  const blockSchemas = collectBlockSchemas(types, schema);
  const lines = [
    "<!-- generated by scripts/generate-section-usage.mjs; edit Liquid schemas, then regenerate -->",
    `# ${schema.name || basename(libraryFile, ".liquid")} — Usage`,
    "",
    `Canonical package: \`${libraryFile}\``,
    "",
    `Installed mirror: \`${runtimeFile}\``,
    "",
    "The section owns layout and color context only. Content and behavior are supplied by the block composition below.",
    "",
    "## Section settings",
    "",
    settingsTable(schema.settings),
    "",
    "## Accepted top-level blocks",
    "",
  ];

  if (types.length) {
    lines.push("| Type | Contract |", "| --- | --- |");
    for (const type of types)
      lines.push(
        `| \`${type}\` | ${blockDescription(
          type,
          schema.blocks?.find((b) => b.type === type)
        )} |`
      );
  } else {
    lines.push("_No blocks are accepted._");
  }

  for (const [type, blockSchema] of blockSchemas) {
    lines.push(
      "",
      `## Block: \`${type}\``,
      "",
      settingsTable(blockSchema.settings),
      "",
      "Allowed children:",
      ""
    );
    const children = childTypes(blockSchema);
    lines.push(children.length ? children.map((child) => `- \`${child}\``).join("\n") : "- None");
  }

  lines.push(
    "",
    "All public foundational blocks also inherit visibility, custom class, top/bottom margin, and anchor-ID controls.",
    ""
  );
  return lines.join("\n");
}

for (const [libraryFile, runtimeFile] of mirrors) {
  const usagePath = join(root, dirname(libraryFile), "usage.md");
  const expected = documentFor(libraryFile, runtimeFile);
  if (checkOnly) {
    if (readFileSync(usagePath, "utf8") !== expected) errors.push(relative(root, usagePath));
  } else {
    writeFileSync(usagePath, expected);
  }
}

const sourcePaths = [
  ...mirrors.map(([libraryFile]) => join(root, libraryFile)),
  ...readdirSync(blocksDir)
    .filter((file) => file.endsWith(".liquid"))
    .map((file) => join(blocksDir, file)),
  fileURLToPath(import.meta.url),
];
const usagePaths = mirrors.map(([libraryFile]) => join(root, dirname(libraryFile), "usage.md"));
const manifestPath = join(root, "section-library/.usage-manifest.json");
const manifest = `${JSON.stringify({ sourceHash: fingerprint(sourcePaths), usageHash: fingerprint(usagePaths) }, null, 2)}\n`;
if (checkOnly) {
  if (readFileSync(manifestPath, "utf8") !== manifest) errors.push(relative(root, manifestPath));
} else {
  writeFileSync(manifestPath, manifest);
}

if (errors.length) {
  console.error("Generated section usage documentation is stale:");
  errors.forEach((path) => console.error(`- ${path}`));
  process.exit(1);
}

console.log(
  `${checkOnly ? "Validated" : "Generated"} usage documentation for ${mirrors.length} section packages.`
);
